import { randomUUID } from 'node:crypto';
import { rmSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { parse as parseDotenv } from 'dotenv';
import { all, get, run, tx } from './db.ts';
import { decodeEnc, decryptValue, encodeEnc, encryptValue, isEncFile } from './crypto.ts';
import { ROOT, docsDir, ensureDir, knowledgeDir, serviceDir, testsDir } from './paths.ts';
import { broadcast } from './hub.ts';

export interface Service {
  id: string;
  name: string;
  baseUrl: string | null;
  notes: string | null;
  createdAt: number;
}

export interface SecretMeta {
  key: string;
  sensitive: boolean;
  /** Present only for non-sensitive keys (URLs, usernames, flags). */
  value?: string;
}

interface ServiceRow {
  id: string;
  name: string;
  base_url: string | null;
  notes: string | null;
  created_at: number;
}

const toService = (r: ServiceRow): Service => ({
  id: r.id,
  name: r.name,
  baseUrl: r.base_url,
  notes: r.notes,
  createdAt: r.created_at,
});

const SENSITIVE = /(pass|pwd|secret|token|key|cookie|credential|private|auth|session|cert)/i;
const BASE_URL_KEYS = ['BASE_URL', 'PROBE_BASE_URL', 'APP_URL', 'SITE_URL'];

export const listServices = () =>
  all<ServiceRow>('SELECT * FROM services ORDER BY created_at').map(toService);

export function getService(id: string): Service | undefined {
  const r = get<ServiceRow>('SELECT * FROM services WHERE id = ?', id);
  return r && toService(r);
}

export function requireService(id: string): Service {
  const s = getService(id);
  if (!s) throw new HttpError(404, `Service ${id} not found`);
  return s;
}

export class HttpError extends Error {
  status: number;
  constructor(status: number, message: string) {
    super(message);
    this.status = status;
  }
}

function normalizeUrl(raw: string | null | undefined): string | null {
  const v = raw?.trim();
  if (!v) return null;
  let u: URL;
  try {
    u = new URL(v);
  } catch {
    throw new HttpError(400, `Not a valid URL: ${v}`);
  }
  if (u.protocol !== 'http:' && u.protocol !== 'https:') throw new HttpError(400, 'URL must start with http:// or https://');
  return u.origin + (u.pathname === '/' ? '' : u.pathname.replace(/\/$/, ''));
}

export function createService(input: { name: string; baseUrl?: string; notes?: string }): Service {
  const name = input.name?.trim();
  if (!name) throw new HttpError(400, 'Service name is required');
  if (get('SELECT 1 FROM services WHERE lower(name) = lower(?)', name)) throw new HttpError(409, `A service named "${name}" already exists`);
  const id = randomUUID().slice(0, 8);
  run('INSERT INTO services (id, name, base_url, notes, created_at) VALUES (?,?,?,?,?)', id, name, normalizeUrl(input.baseUrl), input.notes?.trim() || null, Date.now());
  scaffold(id);
  broadcast({ type: 'service', serviceId: id });
  return requireService(id);
}

export function updateService(id: string, patch: { name?: string; baseUrl?: string | null; notes?: string | null }): Service {
  const cur = requireService(id);
  const name = patch.name?.trim() || cur.name;
  const baseUrl = patch.baseUrl === undefined ? cur.baseUrl : normalizeUrl(patch.baseUrl);
  const notes = patch.notes === undefined ? cur.notes : patch.notes?.trim() || null;
  run('UPDATE services SET name = ?, base_url = ?, notes = ? WHERE id = ?', name, baseUrl, notes, id);
  broadcast({ type: 'service', serviceId: id });
  return requireService(id);
}

export function deleteService(id: string) {
  requireService(id);
  run('DELETE FROM services WHERE id = ?', id);
  rmSync(serviceDir(id), { recursive: true, force: true });
  broadcast({ type: 'service', serviceId: id });
}

/** Create the folders Claude and Playwright work in. Safe to call repeatedly. */
export function scaffold(id: string) {
  ensureDir(docsDir(id));
  ensureDir(knowledgeDir(id));
  const tests = ensureDir(testsDir(id));
  ensureDir(join(tests, 'specs'));
  const posix = (p: string) => p.replaceAll('\\', '/');
  // Specs and the shared fixture must load the same way (ESM), or Playwright loads two copies.
  writeFileSync(join(tests, 'package.json'), '{ "private": true, "type": "module" }\n');
  // Regenerated on every scaffold so path changes (moving the app) heal themselves.
  writeFileSync(
    join(tests, 'probe.ts'),
    `// Generated by Probe. Import { test, expect } from here so the dashboard can follow the run.\nexport * from '${posix(join(ROOT, 'reporter', 'fixture.ts'))}';\n`,
  );
  writeFileSync(
    join(tests, 'playwright.config.ts'),
    `// Plain object on purpose: this folder has no node_modules, so it must not import anything.
export default {
  testDir: './specs',
  outputDir: './.results',
  fullyParallel: false,
  workers: 1,
  retries: 0,
  reporter: [['${posix(join(ROOT, 'reporter', 'probe-reporter.ts'))}'], ['line']],
  use: {
    baseURL: process.env.BASE_URL,
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    locale: 'ko-KR',
  },
};
`,
  );
  if (!existsSync(join(tests, 'README.md'))) {
    writeFileSync(
      join(tests, 'README.md'),
      `# Test workspace\n\nWrite Playwright specs in \`specs/\`. Import from \`../probe.ts\`:\n\n\`\`\`ts\nimport { test, expect, view } from '../probe.ts';\n\`\`\`\n\nCredentials arrive as environment variables (\`process.env.<KEY>\`). Never hard-code them.\n`,
    );
  }
}

export function scaffoldAll() {
  for (const s of listServices()) scaffold(s.id);
}

// ---------------------------------------------------------------- secrets

export function listSecrets(serviceId: string): SecretMeta[] {
  requireService(serviceId);
  return all<{ key: string; value: string; sensitive: number }>('SELECT key, value, sensitive FROM secrets WHERE service_id = ? ORDER BY key', serviceId).map(
    (r) => (r.sensitive ? { key: r.key, sensitive: true } : { key: r.key, sensitive: false, value: decryptValue(r.value) }),
  );
}

/** Accepts plain dotenv text or a passphrase-protected `.enc`. Returns the keys that were written. */
export function importEnv(serviceId: string, text: string, passphrase?: string): { keys: string[]; encrypted: boolean } {
  const svc = requireService(serviceId);
  const encrypted = isEncFile(text);
  if (encrypted && !passphrase) throw new HttpError(422, 'This .enc file needs a passphrase');
  const plain = encrypted ? decodeEnc(text, passphrase!) : text;
  const entries = Object.entries(parseDotenv(plain));
  if (entries.length === 0) throw new HttpError(422, 'No KEY=VALUE lines found in the file');
  tx(() => {
    for (const [key, value] of entries) {
      run(
        `INSERT INTO secrets (service_id, key, value, sensitive) VALUES (?,?,?,?)
         ON CONFLICT(service_id, key) DO UPDATE SET value = excluded.value, sensitive = excluded.sensitive`,
        serviceId,
        key,
        encryptValue(value),
        SENSITIVE.test(key) ? 1 : 0,
      );
    }
  });
  if (!svc.baseUrl) {
    const found = BASE_URL_KEYS.map((k) => parseDotenv(plain)[k]).find(Boolean);
    if (found) {
      try {
        run('UPDATE services SET base_url = ? WHERE id = ?', normalizeUrl(found), serviceId);
      } catch {
        /* an unparsable BASE_URL in the file should not fail the import */
      }
    }
  }
  broadcast({ type: 'service', serviceId });
  return { keys: entries.map(([k]) => k), encrypted };
}

export function deleteSecret(serviceId: string, key: string) {
  requireService(serviceId);
  run('DELETE FROM secrets WHERE service_id = ? AND key = ?', serviceId, key);
  broadcast({ type: 'service', serviceId });
}

export function exportEnc(serviceId: string, passphrase: string): string {
  requireService(serviceId);
  if (passphrase.length < 8) throw new HttpError(400, 'Passphrase must be at least 8 characters');
  const rows = all<{ key: string; value: string }>('SELECT key, value FROM secrets WHERE service_id = ? ORDER BY key', serviceId);
  const body = rows.map((r) => `${r.key}=${JSON.stringify(decryptValue(r.value))}`).join('\n');
  return encodeEnc(body, passphrase);
}

/** Values that must never reach logs, defects or the screen. Longest first so overlaps redact cleanly. */
export function sensitiveValues(serviceId: string): string[] {
  return all<{ value: string }>('SELECT value FROM secrets WHERE service_id = ? AND sensitive = 1', serviceId)
    .map((r) => decryptValue(r.value))
    .filter((v) => v.length >= 4)
    .sort((a, b) => b.length - a.length);
}

/** Decrypted environment for a test process. Never returned over HTTP or MCP. */
export function runtimeEnv(serviceId: string): Record<string, string> {
  const svc = requireService(serviceId);
  const env: Record<string, string> = {};
  for (const r of all<{ key: string; value: string }>('SELECT key, value FROM secrets WHERE service_id = ?', serviceId)) env[r.key] = decryptValue(r.value);
  if (svc.baseUrl) env.BASE_URL = svc.baseUrl;
  return env;
}
