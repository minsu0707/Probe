/**
 * The on-disk workspace Claude and Playwright work in, one per service:
 *
 *   data/services/<id>/
 *     docs/        uploaded source documents (+ extracted text for Office files)
 *     knowledge/   Markdown written by the learning job
 *     tests/       Playwright workspace; specs go in tests/specs/
 *
 * Everything under tests/ except specs/ is generated and rewritten on each start, so
 * moving the Probe folder never leaves a stale absolute path behind.
 */
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, docsDir, ensureDir, knowledgeDir, serviceDir, testsDir } from '../../config.ts';
import { findAll } from './repository.ts';

/** Playwright wants forward slashes in import specifiers, even on Windows. */
const posix = (p: string) => p.replaceAll('\\', '/');

/**
 * Re-exports the shared fixture so specs write `import { test } from '../probe.ts'`.
 * Specs must not import `@playwright/test` themselves: the workspace has no node_modules,
 * and a second copy of Playwright would break `test()` registration.
 */
const fixtureShim = () => `// Generated by Probe. Import { test, expect, view } from here so the dashboard can follow the run.
export * from '${posix(join(ROOT, 'reporter', 'fixture.ts'))}';
`;

/**
 * A plain object, not defineConfig(): this folder has nothing to import from.
 * The reporter is what feeds the live monitor; 'line' keeps a readable console fallback.
 */
const playwrightConfig = () => `// Generated by Probe. Do not edit; changes are overwritten.
export default {
  testDir: './specs',
  outputDir: './.results',
  fullyParallel: false,
  workers: 1,
  retries: 0,
  reporter: [['${posix(join(ROOT, 'reporter', 'probe-reporter.ts'))}'], ['line']],
  use: {
    baseURL: process.env.BASE_URL,
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    locale: 'ko-KR',
  },
};
`;

const readme = `# Test workspace

Write Playwright specs in \`specs/\`. Import from \`../probe.ts\`:

\`\`\`ts
import { test, expect, view } from '../probe.ts';
\`\`\`

Credentials arrive as environment variables (\`process.env.<KEY>\`). Never hard-code them.
`;

export function scaffoldWorkspace(serviceId: string): void {
  ensureDir(docsDir(serviceId));
  ensureDir(knowledgeDir(serviceId));
  const tests = ensureDir(testsDir(serviceId));
  ensureDir(join(tests, 'specs'));

  // "type": "module" makes specs and the shared fixture load the same way (ESM).
  writeFileSync(join(tests, 'package.json'), '{ "private": true, "type": "module" }\n');
  writeFileSync(join(tests, 'probe.ts'), fixtureShim());
  writeFileSync(join(tests, 'playwright.config.ts'), playwrightConfig());
  if (!existsSync(join(tests, 'README.md'))) writeFileSync(join(tests, 'README.md'), readme);
}

export const scaffoldAllWorkspaces = (): void => findAll().forEach((s) => scaffoldWorkspace(s.id));

export const removeWorkspace = (serviceId: string): void => rmSync(serviceDir(serviceId), { recursive: true, force: true });
