/** Pure builders for the Windows autostart file, so the quoting can be tested. */

/** VBScript string literal: wrap in quotes, double any quote inside. */
const vbs = (s: string) => `"${s.replaceAll('"', '""')}"`;

/**
 * A .vbs that starts Probe with no console window (window style 0) when the user logs in.
 * A .vbs is used instead of a .cmd because a .cmd in the Startup folder always flashes a window.
 * It runs launch.ts with --no-open: the server starts, the browser stays closed.
 */
export function buildStartupVbs(o: { nodePath: string; launchScript: string; root: string }): string {
  // The command line itself contains quoted paths, which then get quoted again as a VBScript string.
  const command = `"${o.nodePath}" "${o.launchScript}" --no-open --no-pause`;
  return [
    "' Generated by Probe. Starts the server at login. Remove it with: npm run autostart:off",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = ${vbs(o.root)}`,
    `sh.Run ${vbs(command)}, 0, False`,
    '',
  ].join('\r\n');
}
